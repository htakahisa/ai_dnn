def parse_layer(layer_str):
    lines = [line.strip() for line in layer_str.strip("\n").split("\n") if line.strip()]
    if not lines:
        raise ValueError("Macro layer is empty.")
    if any("PASTE_" in line for line in lines):
        raise ValueError("Macro layer still contains a PASTE_* placeholder.")
    width = len(lines[0])
    if any(len(line) != width for line in lines):
        raise ValueError("Macro layer rows have inconsistent widths.")
    for line in lines:
        for ch in line:
            if ch not in "01234567":
                raise ValueError(f"Invalid macro map character: {ch!r}")
    return [[int(ch) for ch in line] for line in lines]


def find_marker_cells(layer_str, marker):
    grid = parse_layer(layer_str)
    return [
        (r, c)
        for r, row in enumerate(grid)
        for c, value in enumerate(row)
        if value == int(marker)
    ]


def marker_groups(layer_str, marker_dict):
    return {
        name: find_marker_cells(layer_str, marker)
        for name, marker in marker_dict.items()
    }


def validate_layers():
    layers = {
        "ZONE": parse_layer(MACRO_ZONE_STR),
        "TACTICAL": parse_layer(MACRO_TACTICAL_STR),
        "ROTATE_INFO": parse_layer(MACRO_ROTATE_INFO_STR),
        "CONTROL": parse_layer(MACRO_CONTROL_STR),
        "ROLE": parse_layer(MACRO_ROLE_STR),
    }
    names = list(layers)
    base = layers[names[0]]
    height = len(base)
    width = len(base[0])
    for name, grid in layers.items():
        if len(grid) != height or any(len(row) != width for row in grid):
            raise ValueError(f"{name}: map size mismatch")
    for r in range(height):
        for c in range(width):
            wall_flags = [layers[name][r][c] == 1 for name in names]
            if len(set(wall_flags)) != 1:
                values = ", ".join(f"{name}={layers[name][r][c]}" for name in names)
                raise ValueError(f"Wall mismatch at ({r}, {c}): {values}")
    return True


def print_summary():
    validate_layers()
    specs = (
        ("ZONE", MACRO_ZONE_STR, ZONE_MARKERS),
        ("TACTICAL", MACRO_TACTICAL_STR, TACTICAL_MARKERS),
        ("ROTATE_INFO", MACRO_ROTATE_INFO_STR, ROTATE_INFO_MARKERS),
        ("CONTROL", MACRO_CONTROL_STR, CONTROL_MARKERS),
        ("ROLE", MACRO_ROLE_STR, ROLE_MARKERS),
    )
    print("[GC Macro Map] layers: OK")
    for label, layer, markers in specs:
        print(f"\n[{label}]")
        groups = marker_groups(layer, markers)
        for name, cells in groups.items():
            print(f"  {name:20s}: {len(cells):3d} cells")


if __name__ == "__main__":
    print_summary()
